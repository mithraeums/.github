#!/usr/bin/env python3
"""Mithraeum icon system — one ink on one ground (black and white, 2026-10-30).

Each product is one block katakana from its name, printed in ink on paper with a faint second
impression of the same ink knocked out of register, the way a press misprints: hako コ (the
character is drawn as a box), hake ケ, hakm ム, studio ス. The parent, mithraeum, is Mithras'
Phrygian cap. Paper by day (sumi on washi), night in dark mode (bone on void). The old riso
look printed ultramarine with a vermilion second ink; both are gone.

The glyph outlines are from Dela Gothic One (SIL Open Font Licence), converted
to paths once and kept here, so rendering needs no font and no network.

    python3 make-icons.py     # write the SVG masters: <name>.svg (paper), <name>-night.svg,
                              # <name>-auto.svg (follows the system theme, for favicons)
    sh build.sh               # rasterise PNG + icns + ico into each project
"""

import os

OUT = os.path.dirname(os.path.abspath(__file__))

INKS = {
	"paper": ("#ece7da", "#14130f", 0.14),   # washi, sumi, ghost opacity
	"night": ("#0d0c0a", "#e6e0d1", 0.18),   # void, bone
}
MISREG = (14, 9)      # how far the second impression lands from the first

GLYPHS = {
 "コ": "<path transform=\"translate(81.1 387.6) scale(0.3513 -0.3513)\" d=\"M81 505V726H925V23H647V44H71V279H650V505Z\"/>",
 "ケ": "<path transform=\"translate(108.7 368.4) scale(0.2988 -0.2988)\" d=\"M995 688Q975 561 975 463H918Q895 361 846.0 276.0Q797 191 725 133Q668 86 596.0 57.0Q524 28 416.5 10.5Q309 -7 143 -16Q111 74 84.0 130.0Q57 186 23 231Q66 229 140 229Q86 314 -9 396Q94 455 148.0 546.0Q202 637 213 768H494Q487 728 479 688ZM647 463H397L382 437Q319 327 215 230Q329 234 399.5 251.5Q470 269 519 302Q561 331 595.5 372.5Q630 414 647 463Z\"/>",
 "ム": "<path transform=\"translate(103.6 370.5) scale(0.3030 -0.3030)\" d=\"M753 -5Q744 32 737 56Q564 27 396.0 12.5Q228 -2 49 -8L47 13Q39 89 31.5 140.0Q24 191 8 239H105Q205 505 265 764L538 725Q515 661 498.5 612.0Q482 563 471 530Q414 358 373 246Q540 255 664 274Q614 393 541 522L780 599Q859 454 911.0 331.0Q963 208 998 80Q934 64 878.0 44.0Q822 24 753 -5Z\"/>",
 "ス": "<path transform=\"translate(98.4 368.7) scale(0.3175 -0.3175)\" d=\"M850 -10Q720 50 550 143Q391 46 200 -7Q162 54 123.0 107.0Q84 160 24 227Q235 252 383.5 319.5Q532 387 631 500H84V716L844 720L939 510Q852 385 741 285Q857 241 969 228Q889 91 850 -10Z\"/>"
}

CAP = ("M148 396 L148 300 C148 196 206 124 286 116 C346 110 392 140 396 186 "
       "C398 214 380 232 360 228 C348 226 342 214 346 204 C330 196 314 206 316 232 "
       "C320 290 352 340 364 396 Z")


def cap():
	return f'<path d="{CAP}"/><rect x="128" y="384" width="256" height="40"/>'


PRODUCTS = {
	"hako":      lambda: GLYPHS["コ"],
	"hake":      lambda: GLYPHS["ケ"],
	"hakm":      lambda: GLYPHS["ム"],
	"studio":    lambda: GLYPHS["ス"],
	"mithraeum": cap,
}


HEAD = '<?xml version="1.0" encoding="UTF-8"?>\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">\n'


def svg(name, mark, variant):
	ground, ink, ghost = INKS[variant]
	dx, dy = MISREG
	return f'''{HEAD}	<!-- mithraeum icon system — generated by assets/icons/make-icons.py, do not hand-edit. {name}, {variant} -->
	<rect width="512" height="512" rx="112" fill="{ground}"/>
	<g fill="{ink}" opacity="{ghost}" transform="translate({dx} {dy})">{mark}</g>
	<g fill="{ink}">{mark}</g>
</svg>
'''


def svg_touch(name, mark):
	"""The home screen's icon: full-bleed, since iOS rounds it and fills anything transparent itself,
	and one flat light mark on black, since a tinted home screen recolors by brightness and the
	paper tile with its second impression came out dark on dark with a bright edge."""
	ground, ink, _ = INKS["night"]
	return f'''{HEAD}	<!-- mithraeum icon system — generated by assets/icons/make-icons.py, do not hand-edit. {name}, touch -->
	<rect width="512" height="512" fill="{ground}"/>
	<g fill="{ink}">{mark}</g>
</svg>
'''


def svg_auto(name, mark):
	"""One file, both inks: paper by default, night under prefers-color-scheme: dark."""
	(pg, pi, po), (ng, ni, no) = INKS["paper"], INKS["night"]
	dx, dy = MISREG
	return f'''{HEAD}	<!-- mithraeum icon system — generated by assets/icons/make-icons.py, do not hand-edit. {name}, follows the system theme -->
	<style>.g{{fill:{pg}}}.i{{fill:{pi}}}.o{{opacity:{po}}}@media (prefers-color-scheme: dark){{.g{{fill:{ng}}}.i{{fill:{ni}}}.o{{opacity:{no}}}}}</style>
	<rect class="g" width="512" height="512" rx="112"/>
	<g class="i o" transform="translate({dx} {dy})">{mark}</g>
	<g class="i">{mark}</g>
</svg>
'''


if __name__ == "__main__":
	for name, mark in PRODUCTS.items():
		files = {f"{name}.svg": svg(name, mark(), "paper"), f"{name}-night.svg": svg(name, mark(), "night"),
		         f"{name}-auto.svg": svg_auto(name, mark())}
		if name == "studio":
			files[f"{name}-touch.svg"] = svg_touch(name, mark())
		for fn, body in files.items():
			with open(os.path.join(OUT, fn), "w") as f:
				f.write(body)
		print(f"wrote {name}.svg, {name}-night.svg, {name}-auto.svg")
